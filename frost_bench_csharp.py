def csharp_artifact_dir(root: pathlib.Path, tool: str) -> pathlib.Path:
    if tool == "dotnet":
        return root / ".dotnet/bin/App" / CSHARP_CONFIGURATION / CSHARP_TARGET_FRAMEWORK
    pattern = ".frost/out/*/bin" if tool in GENERATED_TOOLS else ".frost/out/*/app"
    matches = sorted(path for path in root.glob(pattern) if path.is_dir())
    if len(matches) != 1:
        raise RuntimeError(f"{tool}: expected one artifact directory matching {pattern}, found {len(matches)}")
    return matches[0]


def clean_csharp_outputs(root: pathlib.Path, tool: str) -> None:
    """Remove build outputs and build state, keeping restore results.

    Restore is not part of any timed build (every frontend runs
    ``--no-restore`` or never restores), so ``project.assets.json`` stays."""
    if tool.startswith("frost-"):
        shutil.rmtree(root / ".frost", ignore_errors=True)
    shutil.rmtree(root / ".dotnet/bin", ignore_errors=True)
    for project in CSHARP_PROJECTS:
        shutil.rmtree(root / ".dotnet/obj" / project / CSHARP_CONFIGURATION, ignore_errors=True)


def csharp_build_command(
    tool: str,
    frost: str | None,
    info: dict[str, Any],
    jobs: int,
    events: pathlib.Path,
) -> list[str]:
    if tool.startswith("frost-"):
        if frost is None:
            raise FileNotFoundError("frost")
        return [
            frost,
            "build",
            "--workspace",
            ".",
            "--jobs",
            str(max(1, jobs)),
            "--no-tui",
            "--build-event-json",
            events.as_posix(),
        ]
    return [
        info["dotnet"],
        "build",
        "src/App/App.csproj",
        "--no-restore",
        "-nologo",
        "-v:q",
        "-c",
        CSHARP_CONFIGURATION,
        f"-m:{max(1, jobs)}",
    ]


def read_frost_events(events: pathlib.Path) -> dict[str, Any]:
    """Which actions ran, and for how long, from Frost's own event stream."""
    executed: list[str] = []
    action_ms = 0
    cached = 0
    elapsed = None
    if events.is_file():
        for line in events.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            event = json.loads(line)
            if event.get("event") == "action_finished":
                if event.get("cached"):
                    cached += 1
                else:
                    executed.append(event.get("desc", ""))
                    action_ms += int(event.get("duration_ms") or 0)
            elif event.get("event") == "build_finished":
                elapsed = event.get("elapsed_ms")
    return {
        "executed_actions": sorted(executed),
        "executed_action_ms": action_ms,
        "cached_actions": cached,
        "frost_elapsed_ms": elapsed,
    }


def compiled_projects(root: pathlib.Path, tool: str, before: dict[str, float]) -> list[str]:
    """Projects whose intermediate assembly MSBuild rewrote during a build."""
    if tool in GENERATED_TOOLS:
        return []
    return sorted(
        project for project, mtime in csharp_obj_mtimes(root).items() if before.get(project) != mtime
    )


def csharp_obj_mtimes(root: pathlib.Path) -> dict[str, float]:
    mtimes = {}
    for project in CSHARP_PROJECTS:
        path = (
            root / ".dotnet/obj" / project / CSHARP_CONFIGURATION / CSHARP_TARGET_FRAMEWORK / f"{project}.dll"
        )
        if path.is_file():
            mtimes[project] = path.stat().st_mtime_ns
    return mtimes


def run_csharp_tool(
    root: pathlib.Path,
    tool: str,
    frost: str | None,
    info: dict[str, Any],
    jobs: int,
    state_root: pathlib.Path,
) -> tuple[float, dict[str, Any]]:
    if tool in GENERATED_TOOLS:
        verify_import_current(root)
    events = state_root / f"events-{tool}.ndjson"
    if events.exists():
        events.unlink()
    before = csharp_obj_mtimes(root)
    command = csharp_build_command(tool, frost, info, jobs, events)
    environment = dotnet_environment(state_root)
    start = time.perf_counter()
    completed = subprocess.run(
        command,
        cwd=root,
        env=environment,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        check=False,
    )
    elapsed_ms = (time.perf_counter() - start) * 1000
    if completed.returncode != 0:
        tail = "\n".join(completed.stdout.splitlines()[-40:])
        raise RuntimeError(f"{tool} failed with exit {completed.returncode}: {' '.join(command)}\n{tail}")
    observation: dict[str, Any] = {}
    if tool.startswith("frost-"):
        observation.update(read_frost_events(events))
    if tool not in GENERATED_TOOLS:
        observation["msbuild_compiled_projects"] = compiled_projects(root, tool, before)
    return elapsed_ms, observation


def verify_csharp_output(
    root: pathlib.Path,
    tool: str,
    expected_total: int,
    info: dict[str, Any],
    state_root: pathlib.Path,
) -> dict[str, Any]:
    """Run the application and fingerprint the assemblies it is made of."""
    directory = csharp_artifact_dir(root, tool)
    assemblies = {}
    for project in CSHARP_PROJECTS:
        path = directory / f"{project}.dll"
        if not path.is_file():
            raise RuntimeError(f"{tool} did not produce {project}.dll in {directory}")
        assemblies[f"{project}.dll"] = hashlib.sha256(path.read_bytes()).hexdigest()
    runtime_config = directory / "App.runtimeconfig.json"
    if not runtime_config.is_file():
        raise RuntimeError(f"{tool} did not produce App.runtimeconfig.json")
    completed = subprocess.run(
        [info["dotnet"], (directory / "App.dll").as_posix()],
        cwd=root,
        env=dotnet_environment(state_root),
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )
    if completed.returncode != 0 or completed.stdout.strip() != str(expected_total):
        raise RuntimeError(
            f"{tool} application printed {completed.stdout.strip()!r} (exit "
            f"{completed.returncode}, stderr {completed.stderr.strip()[-400:]!r}); "
            f"expected {expected_total}"
        )
    semantic = hashlib.sha256(
        json.dumps(
            {
                "stdout": completed.stdout.strip(),
                "assemblies": sorted(assemblies),
                "runtimeconfig": json.loads(runtime_config.read_text(encoding="utf-8")),
            },
            sort_keys=True,
        ).encode()
    ).hexdigest()
    return {
        "stdout": completed.stdout.strip(),
        "assemblies_sha256": assemblies,
        "assembly_set_sha256": hashlib.sha256(
            json.dumps(assemblies, sort_keys=True).encode()
        ).hexdigest(),
        "semantic_sha256": semantic,
        "extra_files": sorted(
            path.name
            for path in directory.iterdir()
            if path.is_file() and path.name not in {*assemblies, "App.runtimeconfig.json"}
        ),
    }


def csharp_configuration_metrics(root: pathlib.Path, tool: str) -> dict[str, Any]:
    authored = ["Directory.Build.props", *[f"src/{p}/{p}.csproj" for p in CSHARP_PROJECTS]]
    files = list(authored)
    if tool.startswith("frost-"):
        files.append("frost.toml")
    texts = {path: (root / path).read_text(encoding="utf-8") for path in files}
    metrics: dict[str, Any] = {
        "files": files,
        "configuration_lines": sum(len(text.splitlines()) for text in texts.values()),
        "configuration_bytes": sum(len(text.encode()) for text in texts.values()),
        "authored_msbuild_lines": sum(len(texts[path].splitlines()) for path in authored),
        "authored_msbuild_bytes": sum(len(texts[path].encode()) for path in authored),
    }
    if tool.startswith("frost-"):
        metrics["frost_manifest_lines"] = len(texts["frost.toml"].splitlines())
        metrics["frost_manifest_bytes"] = len(texts["frost.toml"].encode())
        metrics["frost_manifest_is_generated"] = tool in GENERATED_TOOLS
    if tool in GENERATED_TOOLS:
        metrics["generated_toolchain_bundle_excluded_from_configuration_size"] = [
            ".dotnet-sdk",
            ".dotnet-gen",
        ]
    return metrics


