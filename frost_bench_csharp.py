def measure_jvm_compiler_startup(
    base: pathlib.Path,
    size: int,
    iterations: int,
) -> dict[str, Any]:
    """Cold one-shot compiles of the same N-class library by javac and kotlinc.

    This is not a Kotlin benchmark; it measures the per-invocation cost a
    native ``kotlinc`` rule would pay without a persistent worker, next to the
    javac cost Frost already pays for Java."""
    root = base / "jvm-probe"
    if root.exists():
        shutil.rmtree(root)
    write_jvm_probe_sources(root, size)
    compilers = {
        "javac": os.environ.get("JAVAC_BIN") or shutil.which("javac"),
        "kotlinc": os.environ.get("KOTLINC_BIN") or shutil.which("kotlinc"),
    }
    samples: dict[str, list[float]] = {name: [] for name in JVM_PROBE_TOOLS}
    results: dict[str, Any] = {}
    active = [name for name in JVM_PROBE_TOOLS if compilers[name]]
    for name in JVM_PROBE_TOOLS:
        if not compilers[name]:
            results[name] = {
                "status": "skipped",
                "reason": f"{name} not found; set {name.upper()}_BIN to include it",
            }

    def command(name: str, output: pathlib.Path) -> list[str]:
        if name == "javac":
            return [
                compilers["javac"],
                "--release",
                "21",
                "-d",
                output.as_posix(),
                *sorted(path.as_posix() for path in (root / "java/bench").glob("*.java")),
            ]
        return [
            compilers["kotlinc"],
            "-jvm-target",
            "21",
            "-no-reflect",
            "-d",
            output.as_posix(),
            *sorted(path.as_posix() for path in (root / "kotlin/bench").glob("*.kt")),
        ]

    for iteration in range(iterations + 1):
        order = active if iteration % 2 == 0 else list(reversed(active))
        for name in order:
            output = root / f"out-{name}"
            shutil.rmtree(output, ignore_errors=True)
            output.mkdir()
            start = time.perf_counter()
            completed = subprocess.run(
                command(name, output),
                cwd=root,
                text=True,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                check=False,
            )
            elapsed = (time.perf_counter() - start) * 1000
            if completed.returncode != 0:
                results[name] = {"status": "failed", "reason": completed.stdout[-1500:]}
                active = [tool for tool in active if tool != name]
                continue
            classes = len(list(output.rglob("*.class")))
            if classes < size:
                results[name] = {"status": "failed", "reason": f"only {classes} classes produced"}
                active = [tool for tool in active if tool != name]
                continue
            if iteration > 0:  # the first round warms the page cache only
                samples[name].append(elapsed)
    for name in active:
        version = subprocess.run(
            [compilers[name], "-version"],
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            check=False,
        ).stdout.strip()
        results[name] = {
            "status": "ok",
            "version": version.splitlines()[-1] if version else None,
            "classes": size,
            "cold_compile": summarize(samples[name]),
        }
    if all(results.get(name, {}).get("status") == "ok" for name in JVM_PROBE_TOOLS):
        results["kotlinc_over_javac_median"] = round(
            results["kotlinc"]["cold_compile"]["median_ms"] / results["javac"]["cold_compile"]["median_ms"],
            3,
        )
    return {
        "question": "per-invocation cost of a native kotlinc rule without a persistent worker",
        "sources_per_compiler": size,
        "warmup_rounds_discarded": 1,
        "execution_order": "alternating; reversed every round",
        "results": results,
    }


