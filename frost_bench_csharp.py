def csharp_value_class(project: str, index: int) -> str:
    return f"{project}Value{index:03d}"


def csharp_values(size: int) -> dict[str, list[int]]:
    return {
        project: [CSHARP_VALUE_BASE[project] + index for index in range(size)]
        for project in CSHARP_PROJECTS
    }


def csharp_expected_total(values: dict[str, list[int]], extra: int = 0) -> int:
    """What the application prints: every value once, plus Service's direct
    use of ``CoreValue000`` (the edge that makes the graph a diamond), plus
    whatever a correctness probe added."""
    return sum(sum(project_values) for project_values in values.values()) + values["Core"][0] + extra


def csharp_sources(size: int) -> list[str]:
    sources = []
    for project in CSHARP_PROJECTS:
        sources.extend(
            f"src/{project}/{csharp_value_class(project, index)}.cs"
            for index in range(size)
        )
        sources.append(
            f"src/{project}/Program.cs" if project == "App" else f"src/{project}/{project}Total.cs"
        )
    sources.append("src/Core/CoreConstants.cs")
    return sorted(sources)


def write_csharp_constants(root: pathlib.Path, offset: int) -> None:
    """A public constant Model reads. C# inlines constants into the consumer's
    IL, so a change here is only correct if every consumer recompiles -- the
    classic stale-constant trap an API-level compile-avoidance scheme must not
    fall into."""
    (root / "src/Core/CoreConstants.cs").write_text(
        "\n".join(
            [
                "namespace Bench.Core;",
                "",
                "public static class CoreConstants",
                "{",
                f"    public const ulong Offset = {offset}UL;",
                "}",
                "",
            ]
        ),
        encoding="utf-8",
    )


def write_csharp_value(root: pathlib.Path, project: str, index: int, value: int) -> None:
    name = csharp_value_class(project, index)
    (root / "src" / project / f"{name}.cs").write_text(
        "\n".join(
            [
                f"namespace Bench.{project};",
                "",
                f"public static class {name}",
                "{",
                f"    public static ulong Get() => {value}UL;",
                "}",
                "",
            ]
        ),
        encoding="utf-8",
    )


def write_csharp_aggregate(root: pathlib.Path, project: str, size: int) -> None:
    additions = [
        f"        total += {csharp_value_class(project, index)}.Get();"
        for index in range(size)
    ]
    upstream = {
        "Core": [],
        "Model": [
            "        total += Bench.Core.CoreTotal.Sum();",
            "        total += Bench.Core.CoreConstants.Offset;",
        ],
        "Service": [
            "        total += Bench.Model.ModelTotal.Sum();",
            "        total += Bench.Core.CoreValue000.Get();",
        ],
    }
    if project == "App":
        (root / "src/App/Program.cs").write_text(
            "\n".join(
                [
                    "namespace Bench.App;",
                    "",
                    "public static class Program",
                    "{",
                    "    public static int Main()",
                    "    {",
                    "        ulong total = Bench.Service.ServiceTotal.Sum();",
                    *additions,
                    "        System.Console.WriteLine(total);",
                    "        return 0;",
                    "    }",
                    "}",
                    "",
                ]
            ),
            encoding="utf-8",
        )
        return
    (root / "src" / project / f"{project}Total.cs").write_text(
        "\n".join(
            [
                f"namespace Bench.{project};",
                "",
                f"public static class {project}Total",
                "{",
                "    public static ulong Sum()",
                "    {",
                "        ulong total = 0;",
                *upstream[project],
                *additions,
                "        return total;",
                "    }",
                "}",
                "",
            ]
        ),
        encoding="utf-8",
    )


def write_csharp_project_file(root: pathlib.Path, project: str) -> None:
    lines = ['<Project Sdk="Microsoft.NET.Sdk">']
    if project == "App":
        lines.extend(
            [
                "  <PropertyGroup>",
                "    <OutputType>Exe</OutputType>",
                "  </PropertyGroup>",
            ]
        )
    references = CSHARP_REFERENCES[project]
    if references:
        lines.append("  <ItemGroup>")
        lines.extend(
            f'    <ProjectReference Include="../{reference}/{reference}.csproj" />'
            for reference in references
        )
        lines.append("  </ItemGroup>")
    lines.extend(["</Project>", ""])
    (root / "src" / project / f"{project}.csproj").write_text("\n".join(lines), encoding="utf-8")


def generate_csharp_sources(root: pathlib.Path, size: int) -> None:
    """Write the frontend-independent part of a workspace: projects and C#."""
    if root.exists():
        shutil.rmtree(root)
    for project in CSHARP_PROJECTS:
        (root / "src" / project).mkdir(parents=True)
        write_csharp_project_file(root, project)
        for index, value in enumerate(csharp_values(size)[project]):
            write_csharp_value(root, project, index, value)
        write_csharp_aggregate(root, project, size)
    write_csharp_constants(root, 0)
    (root / "Directory.Build.props").write_text(DIRECTORY_BUILD_PROPS, encoding="utf-8")
    (root / ".frostignore").write_text(".dotnet/\n", encoding="utf-8")


def csharp_source_digest(root: pathlib.Path) -> str:
    digest = hashlib.sha256()
    for relative in sorted(
        path.relative_to(root).as_posix()
        for path in root.glob("src/**/*")
        if path.is_file() and path.suffix in (".cs", ".csproj")
    ):
        digest.update(relative.encode() + b"\0" + (root / relative).read_bytes() + b"\0")
    return digest.hexdigest()


def csharp_graph_contract(size: int) -> dict[str, Any]:
    payload = json.dumps(
        {
            "projects": list(CSHARP_PROJECTS),
            "references": {key: list(value) for key, value in CSHARP_REFERENCES.items()},
            "sources": csharp_sources(size),
            "values": csharp_values(size),
            "target_framework": CSHARP_TARGET_FRAMEWORK,
            "configuration": CSHARP_CONFIGURATION,
            "directory_build_props": DIRECTORY_BUILD_PROPS,
        },
        sort_keys=True,
        separators=(",", ":"),
    ).encode()
    return {
        "language": "C#",
        "shape": "four-project diamond (App -> Service -> Model -> Core, Service -> Core)",
        "project_count": len(CSHARP_PROJECTS),
        "project_reference_edges": sum(len(value) for value in CSHARP_REFERENCES.values()),
        "source_count": len(csharp_sources(size)),
        "value_files_per_project": size,
        "initial_expected_stdout": str(csharp_expected_total(csharp_values(size))),
        "contract_sha256": hashlib.sha256(payload).hexdigest(),
        "same_source_graph": True,
        "incremental_leaf": "one method body in the top App project changes",
        "incremental_shared": (
            "one method body in the bottom Core project changes; its public API "
            "(reference assembly) does not"
        ),
    }


