"""C#/.NET prototype suite for the language-expansion study (#153).

The same four-project SDK-style graph is built three ways:

* ``dotnet``       -- the incumbent: ``dotnet build`` with MSBuild's own
                      incremental state, node reuse and compiler server;
* ``frost-dotnet`` -- an incumbent-owned boundary: one Frost command target
                      wrapping that same ``dotnet build``;
* ``frost-csc``    -- a generated command boundary: MSBuild evaluates each
                      project once (a design-time ``Compile`` with
                      ``SkipCompilerExecution``), and the generator turns the
                      exact Roslyn argv it would have used into one Frost
                      action per project, with the compiler, reference
                      assemblies and analyzers copied into the workspace as
                      declared inputs.

Every timed build is followed by executing the application and checking the
printed total, so a stale artifact fails the run instead of being timed. The
suite also runs untimed correctness probes (a public-API dependency change and,
for the generated boundary, a toolchain-closure change) and records which
actions actually executed, from Frost's own build event stream.

``docs/32_language_expansion.md`` explains what the numbers do and do not
support.
"""

