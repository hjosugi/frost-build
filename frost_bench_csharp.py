def dotnet_environment(state_root: pathlib.Path) -> dict[str, str]:
    """The environment every .NET process in this suite gets.

    CLI home and the NuGet folder are isolated under the benchmark work
    directory so a run neither reads nor writes the user's ~/.dotnet or
    ~/.nuget. The graph has no package references, so restore never touches
    the network."""
    environment = os.environ.copy()
    environment.update(
        {
            "DOTNET_CLI_TELEMETRY_OPTOUT": "1",
            "DOTNET_NOLOGO": "1",
            "DOTNET_SKIP_FIRST_TIME_EXPERIENCE": "1",
            "DOTNET_GENERATE_ASPNET_CERTIFICATE": "false",
            "DOTNET_CLI_HOME": (state_root / "dotnet-home").as_posix(),
            "NUGET_PACKAGES": (state_root / "nuget-packages").as_posix(),
        }
    )
    return environment


def find_dotnet() -> str | None:
    configured = os.environ.get("DOTNET_BIN")
    if configured:
        return configured if pathlib.Path(configured).is_file() else None
    return shutil.which("dotnet")


def dotnet_info(dotnet: str, environment: dict[str, str]) -> dict[str, Any] | None:
    """SDK version, the SDK directory and the targeting pack the SDK uses."""
    try:
        version = subprocess.check_output(
            [dotnet, "--version"], text=True, env=environment, stderr=subprocess.STDOUT
        ).strip()
    except (OSError, subprocess.SubprocessError):
        return None
    root = pathlib.Path(dotnet).resolve().parent
    sdk = root / "sdk" / version
    roslyn = sdk / "Roslyn" / "bincore"
    if not (roslyn / "csc.dll").is_file():
        return None
    packs = sorted((root / "packs/Microsoft.NETCore.App.Ref").glob("*"))
    runtimes = sorted((root / "shared/Microsoft.NETCore.App").glob("*"))
    return {
        "dotnet": pathlib.Path(dotnet).resolve().as_posix(),
        "dotnet_root": root.as_posix(),
        "sdk_version": version,
        "sdk_dir": sdk.as_posix(),
        "roslyn_dir": roslyn.as_posix(),
        "targeting_pack_versions": [path.name for path in packs],
        "runtime_versions": [path.name for path in runtimes],
    }


def run_checked(
    command: list[str],
    cwd: pathlib.Path,
    environment: dict[str, str],
) -> str:
    completed = subprocess.run(
        command,
        cwd=cwd,
        env=environment,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        check=False,
    )
    if completed.returncode != 0:
        tail = "\n".join(completed.stdout.splitlines()[-40:])
        raise RuntimeError(f"{' '.join(command)} failed with exit {completed.returncode}:\n{tail}")
    return completed.stdout


def dotnet_restore(root: pathlib.Path, dotnet: str, environment: dict[str, str]) -> None:
    run_checked(
        [dotnet, "restore", "src/App/App.csproj", "-nologo", "-v:q"],
        root,
        environment,
    )


