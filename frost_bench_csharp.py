CSHARP_SCHEMA = "frost-bench-csharp-v1"
CSHARP_SCENARIOS = ("clean", "noop", "incremental_leaf", "incremental_shared")
CSHARP_TOOLS = ("frost-csc", "frost-csc-shared", "frost-dotnet", "dotnet")
# Frontends that run Frost's generated per-project csc actions.
GENERATED_TOOLS = ("frost-csc", "frost-csc-shared")
# Dependency order matters: a project may only reference an earlier one.
CSHARP_PROJECTS = ("Core", "Model", "Service", "App")
CSHARP_REFERENCES = {
    "Core": (),
    "Model": ("Core",),
    "Service": ("Model", "Core"),
    "App": ("Service",),
}
CSHARP_VALUE_BASE = {"Core": 0, "Model": 1000, "Service": 2000, "App": 3000}
CSHARP_TARGET_FRAMEWORK = "net10.0"
CSHARP_CONFIGURATION = "Release"
JVM_PROBE_TOOLS = ("javac", "kotlinc")

# The build properties every frontend shares. `DebugType=none` keeps the PDB
# path -- which differs between an MSBuild `obj/` tree and a Frost output tree
# -- out of the assembly, so the equal-artifact check can compare bytes rather
# than trusting a successful exit. PDB production is follow-up work, named in
# docs/32, not an omission this suite hides.
DIRECTORY_BUILD_PROPS = """<Project>
  <!-- Generated by frost_bench_csharp.py (#153). Shared by every frontend. -->
  <PropertyGroup>
    <BaseIntermediateOutputPath>$(MSBuildThisFileDirectory).dotnet/obj/$(MSBuildProjectName)/</BaseIntermediateOutputPath>
    <BaseOutputPath>$(MSBuildThisFileDirectory).dotnet/bin/$(MSBuildProjectName)/</BaseOutputPath>
    <TargetFramework>net10.0</TargetFramework>
    <Nullable>enable</Nullable>
    <ImplicitUsings>disable</ImplicitUsings>
    <Deterministic>true</Deterministic>
    <DebugType>none</DebugType>
    <UseAppHost>false</UseAppHost>
    <IncludeSourceRevisionInInformationalVersion>false</IncludeSourceRevisionInInformationalVersion>
    <GenerateDocumentationFile>false</GenerateDocumentationFile>
  </PropertyGroup>
</Project>
"""


