def design_time_compile_args(
    root: pathlib.Path,
    project: str,
    dotnet: str,
    environment: dict[str, str],
) -> list[str]:
    """The exact csc argv MSBuild would use for ``project``, without compiling.

    This is the design-time build IDEs use: ``SkipCompilerExecution`` runs the
    Csc task without invoking the compiler, and ``ProvideCommandLineArgs``
    returns its argv. ``BuildProjectReferences=false`` keeps it to one
    project; references still resolve to their (future) reference-assembly
    paths. The intermediate directory is cleared first because an up-to-date
    CoreCompile does not run the task at all and so reports nothing."""
    intermediate = root / ".dotnet/obj" / project / CSHARP_CONFIGURATION
    if intermediate.exists():
        shutil.rmtree(intermediate)
    output = run_checked(
        [
            dotnet,
            "msbuild",
            f"src/{project}/{project}.csproj",
            "-nologo",
            "-t:Compile",
            f"-p:Configuration={CSHARP_CONFIGURATION}",
            "-p:BuildProjectReferences=false",
            "-p:SkipCompilerExecution=true",
            "-p:ProvideCommandLineArgs=true",
            "-getItem:CscCommandLineArgs",
        ],
        root,
        environment,
    )
    start = output.find("{")
    if start < 0:
        raise RuntimeError(f"MSBuild returned no item JSON for {project}:\n{output[-2000:]}")
    items = json.loads(output[start:])["Items"]["CscCommandLineArgs"]
    arguments = [item["Identity"] for item in items]
    if not arguments:
        raise RuntimeError(f"MSBuild reported no compiler arguments for {project}")
    return arguments


def runtime_config_json(root: pathlib.Path, dotnet: str, environment: dict[str, str]) -> str:
    """The application's runtimeconfig.json, as MSBuild itself generates it."""
    run_checked(
        [
            dotnet,
            "msbuild",
            "src/App/App.csproj",
            "-nologo",
            # ResolveReferences supplies the framework reference; without it
            # the file names no framework and the host refuses to start.
            "-t:ResolveReferences;GenerateBuildRuntimeConfigurationFiles",
            f"-p:Configuration={CSHARP_CONFIGURATION}",
            "-p:BuildProjectReferences=false",
        ],
        root,
        environment,
    )
    matches = sorted(root.glob(".dotnet/bin/App/**/App.runtimeconfig.json"))
    if len(matches) != 1:
        raise RuntimeError(f"expected one generated App.runtimeconfig.json, found {len(matches)}")
    return matches[0].read_text(encoding="utf-8")


def _link_or_copy(source: pathlib.Path, destination: pathlib.Path) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    if destination.exists():
        return
    try:
        os.link(source, destination)
    except OSError:
        shutil.copy2(source, destination)


def bundle_csharp_toolchain(
    root: pathlib.Path,
    info: dict[str, Any],
    files: set[pathlib.Path],
) -> dict[str, Any]:
    """Copy the compiler and every referenced SDK file into ``.dotnet-sdk``.

    Declared inputs are how a Frost action key sees bytes: the csc apphost is
    only a launcher, and the compiler that decides the output is csc.dll plus
    the Microsoft.CodeAnalysis assemblies beside it. The reference assemblies,
    analyzers and source generators the SDK passes are compiler inputs too --
    a source generator writes code into the assembly. So the whole closure
    lives in the workspace, hard-linked when the file system allows."""
    dotnet_root = pathlib.Path(info["dotnet_root"])
    bundle = root / ".dotnet-sdk"
    roslyn = pathlib.Path(info["roslyn_dir"])
    count = 0
    size = 0
    for path in sorted(roslyn.rglob("*")):
        if path.is_file():
            _link_or_copy(path, bundle / path.relative_to(dotnet_root))
            count += 1
            size += path.stat().st_size
    for path in sorted(files):
        _link_or_copy(path, bundle / path.relative_to(dotnet_root))
        count += 1
        size += path.stat().st_size
    return {"files": count, "bytes": size}


def translate_csc_arguments(
    root: pathlib.Path,
    project: str,
    arguments: list[str],
    info: dict[str, Any],
) -> tuple[list[str], list[str], list[str], set[pathlib.Path], list[tuple[pathlib.Path, str]]]:
    """Rewrite MSBuild's absolute, obj/-relative argv into a Frost action.

    Returns (args, source inputs, api dependencies, SDK files to bundle,
    generated files to copy). Anything this cannot classify is an error: a
    silently dropped argument would be a compiler input missing from the key.
    """
    dotnet_root = pathlib.Path(info["dotnet_root"]).resolve()
    workspace = root.resolve()
    obj = workspace / ".dotnet/obj"
    project_dir = workspace / "src" / project
    args: list[str] = []
    sources: list[str] = []
    dependencies: list[str] = []
    sdk_files: set[pathlib.Path] = set()
    generated: list[tuple[pathlib.Path, str]] = []

    def sdk_relative(path: pathlib.Path) -> str:
        sdk_files.add(path)
        return (pathlib.Path(".dotnet-sdk") / path.relative_to(dotnet_root)).as_posix()

    def generated_relative(path: pathlib.Path) -> str:
        destination = f".dotnet-gen/{project}/{path.name}"
        generated.append((path, destination))
        return destination

    for argument in arguments:
        # MSBuild writes options as `/name[:value]`; on POSIX an absolute
        # source path also starts with `/`, so a path that exists is a file.
        if argument.startswith("/") and pathlib.Path(argument).is_file():
            path = pathlib.Path(argument).resolve()
            if path.is_relative_to(obj):
                relative = generated_relative(path)
            elif path.is_relative_to(workspace):
                relative = path.relative_to(workspace).as_posix()
            else:
                raise RuntimeError(f"source {argument!r} of {project} lies outside the workspace")
            sources.append(relative)
            args.append(relative)
            continue
        option, separator, value = argument.partition(":")
        if argument.startswith("/") and separator and option in ("/out", "/refout"):
            continue
        if argument.startswith("/") and separator and option in (
            "/reference",
            "/analyzer",
            "/analyzerconfig",
        ):
            path = pathlib.Path(value).resolve()
            if path.is_relative_to(dotnet_root):
                args.append(f"{option}:{sdk_relative(path)}")
            elif option == "/reference" and path.is_relative_to(obj):
                referenced = path.relative_to(obj).parts[0]
                if referenced not in CSHARP_PROJECTS or path.name != f"{referenced}.dll":
                    raise RuntimeError(f"unrecognised project reference {value!r} in {project}")
                dependencies.append(referenced)
                args.append(f"/reference:.frost/out/${{config}}/api/{referenced}.dll")
            elif option == "/analyzerconfig" and path.is_relative_to(obj):
                args.append(f"/analyzerconfig:{generated_relative(path)}")
            else:
                raise RuntimeError(f"cannot place {option} input {value!r} for {project}")
            continue
        if argument.startswith("/"):
            args.append(argument)
            continue
        # A source file: relative to the project directory, or generated in obj/.
        path = (project_dir / argument).resolve()
        if path.is_relative_to(obj):
            relative = generated_relative(path)
        elif path.is_relative_to(workspace):
            relative = path.relative_to(workspace).as_posix()
        else:
            raise RuntimeError(f"source {argument!r} of {project} lies outside the workspace")
        sources.append(relative)
        args.append(relative)
    return args, sources, dependencies, sdk_files, generated


def toml_string(value: str) -> str:
    return json.dumps(value)


def toml_array(values: list[str], indent: str = "  ") -> str:
    if not values:
        return "[]"
    return "[\n" + "".join(f"{indent}{toml_string(value)},\n" for value in values) + "]"


def write_csharp_frost_generated(
    root: pathlib.Path,
    compile_args: dict[str, list[str]],
    info: dict[str, Any],
    runtime_config: str,
    *,
    shared: bool = False,
) -> dict[str, Any]:
    """Emit the generated command boundary: one csc action per project, one
    API-copy action per library, and the runtimeconfig beside the app.

    ``shared`` adds ``/shared``: each action's csc process hands the compile
    to Roslyn's compiler server (VBCSCompiler), started on first use from the
    bundled compiler and kept alive between actions and builds. That is the
    persistent worker MSBuild already uses, and the one question #145 asks of
    Frost; the server is outside Frost's process tree, action key and
    sandbox, which is exactly why it is a separate frontend."""
    translated = {}
    all_sdk_files: set[pathlib.Path] = set()
    for project in CSHARP_PROJECTS:
        args, sources, dependencies, sdk_files, generated = translate_csc_arguments(
            root, project, compile_args[project], info
        )
        for source, destination in generated:
            target = root / destination
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, target)
        all_sdk_files |= sdk_files
        translated[project] = (args, sources, dependencies, [dest for _, dest in generated])
    bundle = bundle_csharp_toolchain(root, info, all_sdk_files)

    # Every project passes the same 160-odd reference assemblies, analyzers
    # and SDK analyzer configs. They go into one shared response file -- a
    # declared input, so its bytes are key material exactly as argv is --
    # instead of being repeated in every target.
    def closure_argument(argument: str) -> bool:
        option = argument.split(":", 1)[0]
        return option in ("/reference", "/analyzer", "/analyzerconfig") and ":.dotnet-sdk/" in argument

    closures = {
        project: [argument for argument in translated[project][0] if closure_argument(argument)]
        for project in CSHARP_PROJECTS
    }
    common_closure = closures[CSHARP_PROJECTS[0]]
    if any(closure != common_closure for closure in closures.values()):
        raise RuntimeError("projects disagree about the SDK reference closure; refusing to share it")
    response_file = ".dotnet-gen/sdk-closure.rsp"
    (root / response_file).parent.mkdir(parents=True, exist_ok=True)
    (root / response_file).write_text("\n".join(common_closure) + "\n", encoding="utf-8")
    for project in CSHARP_PROJECTS:
        args, sources, dependencies, generated = translated[project]
        compacted: list[str] = []
        for argument in args:
            if closure_argument(argument):
                if f"@{response_file}" not in compacted:
                    compacted.append(f"@{response_file}")
                continue
            compacted.append(argument)
        translated[project] = (compacted, sources, dependencies, [*generated, response_file])
    (root / ".dotnet-gen/App").mkdir(parents=True, exist_ok=True)
    (root / ".dotnet-gen/App/App.runtimeconfig.json").write_text(runtime_config, encoding="utf-8")

    csc = (
        pathlib.Path(".dotnet-sdk")
        / pathlib.Path(info["roslyn_dir"]).relative_to(info["dotnet_root"])
        / ("csc.exe" if os.name == "nt" else "csc")
    ).as_posix()
    lines = [
        "# Generated by frost_bench_csharp.py (#153): MSBuild evaluated each",
        "# project once; these are the Roslyn invocations it would have made.",
        f"# SDK {info['sdk_version']}; regenerate after changing any .csproj or",
        "# Directory.Build.props (the generator records their digest).",
        "",
        "[workspace]",
        'default_targets = ["app"]',
        "",
        "[toolchain.tools]",
        f"csc = {toml_string(csc)}",
        'cp = "cp"',
        "",
    ]
    environment = f'{{ DOTNET_ROOT = {toml_string(info["dotnet_root"])} }}'
    for project in CSHARP_PROJECTS:
        args, sources, dependencies, generated = translated[project]
        if project == "App":
            # Read by the copy step, so it is an input like any source: an
            # undeclared step input would be a cache key that cannot see it.
            generated = [*generated, ".dotnet-gen/App/App.runtimeconfig.json"]
        name = project.lower()
        outputs = [f".frost/out/${{config}}/bin/{project}.dll"]
        if project != "App":
            outputs.append(f".frost/out/${{config}}/ref/{project}.dll")
            refout = [f"/refout:.frost/out/${{config}}/ref/{project}.dll"]
        else:
            outputs.append(".frost/out/${config}/bin/App.runtimeconfig.json")
            refout = []
        lines.extend(
            [
                f"[target.{name}]",
                'kind = "command"',
                'tool = "csc"',
                f"deps = {toml_array([f'{dependency.lower()}_api' for dependency in dependencies])}",
                f"inputs = {toml_array(sorted(set(sources) | set(generated)) + ['.dotnet-sdk/**/*'])}",
                f"outputs = {toml_array(outputs)}",
                f"args = {toml_array(args + (['/shared'] if shared else []) + ['/out:${out}'] + refout)}",
            ]
        )
        if project == "App":
            lines.append(
                'steps = [{ tool = "cp", args = [".dotnet-gen/App/App.runtimeconfig.json", '
                '".frost/out/${config}/bin/App.runtimeconfig.json"] }]'
            )
        lines.extend([f"env = {environment}", "sandbox = false", ""])
        if project != "App":
            # Consumers compile against the reference assembly. Copying it is
            # the whole point: when an implementation-only edit leaves those
            # bytes unchanged, early cutoff stops here and no dependent project
            # recompiles -- MSBuild's ProduceReferenceAssembly avoidance,
            # expressed as an ordinary content-addressed edge.
            lines.extend(
                [
                    f"[target.{name}_api]",
                    'kind = "command"',
                    'tool = "cp"',
                    f'deps = ["{name}"]',
                    f'args = [".frost/out/${{config}}/ref/{project}.dll", "${{out}}"]',
                    f'outputs = [".frost/out/${{config}}/api/{project}.dll"]',
                    "sandbox = false",
                    "",
                ]
            )
    (root / "frost.toml").write_text("\n".join(lines), encoding="utf-8")
    stamp = {
        "sdk_version": info["sdk_version"],
        "evaluation_inputs_sha256": csharp_evaluation_digest(root),
    }
    (root / ".dotnet-gen/import-stamp.json").write_text(
        json.dumps(stamp, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    return {"toolchain_bundle": bundle, "actions": len(CSHARP_PROJECTS) * 2 - 1}


def csharp_evaluation_digest(root: pathlib.Path) -> str:
    """Digest of what MSBuild evaluation reads: project files and props.

    A generated boundary is only as current as the evaluation it came from;
    ``verify_import_current`` refuses to time a build whose evaluation inputs
    changed after generation."""
    digest = hashlib.sha256()
    for path in sorted([root / "Directory.Build.props", *root.glob("src/*/*.csproj")]):
        digest.update(path.relative_to(root).as_posix().encode() + b"\0" + path.read_bytes())
    return digest.hexdigest()


def verify_import_current(root: pathlib.Path) -> None:
    stamp = json.loads((root / ".dotnet-gen/import-stamp.json").read_text(encoding="utf-8"))
    if stamp["evaluation_inputs_sha256"] != csharp_evaluation_digest(root):
        raise RuntimeError("project files changed after the generated boundary was imported")


