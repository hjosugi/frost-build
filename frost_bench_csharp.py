        "",
        "[toolchain.tools]",
        f"dotnet = {toml_string(info['dotnet'])}",
        "",
        "[target.app]",
        'kind = "command"',
        'tool = "dotnet"',
        f"inputs = {toml_array(['Directory.Build.props', 'src/**/*.cs', 'src/**/*.csproj'])}",
        'output_dirs = [".frost/out/${config}/app"]',
