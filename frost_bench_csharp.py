def generate_csharp_workspace(
    root: pathlib.Path,
    size: int,
    tool: str,
    info: dict[str, Any] | None,
    state_root: pathlib.Path,
    jobs: int = 1,
) -> dict[str, Any]:
    """Generate one frontend's workspace; returns import metadata.

    Without a .NET SDK only the sources are written, so the graph contract is
    still checkable (and unit-testable) on a host that cannot run it."""
    generate_csharp_sources(root, size)
    if info is None:
        return {}
    environment = dotnet_environment(state_root)
    dotnet_restore(root, info["dotnet"], environment)
    if tool in GENERATED_TOOLS:
        start = time.perf_counter()
        compile_args = {
            project: design_time_compile_args(root, project, info["dotnet"], environment)
            for project in CSHARP_PROJECTS
        }
        runtime_config = runtime_config_json(root, info["dotnet"], environment)
        import_ms = (time.perf_counter() - start) * 1000
        metadata = write_csharp_frost_generated(
            root, compile_args, info, runtime_config, shared=tool == "frost-csc-shared"
        )
        # The design-time evaluation leaves obj/ and bin/ state behind; none of
        # it is a Frost input, and the timed builds must not inherit it.
        shutil.rmtree(root / ".dotnet/bin", ignore_errors=True)
        metadata["import_ms"] = round(import_ms, 3)
        metadata["compiler_arguments"] = {
            project: len(arguments) for project, arguments in compile_args.items()
        }
        return metadata
    if tool == "frost-dotnet":
        write_csharp_frost_wrapper(root, info, state_root, jobs)
        return {}
    if tool == "dotnet":
        return {}
    raise ValueError(f"unsupported C# benchmark tool: {tool}")


