def probe_dependency_api_change(
    root: pathlib.Path,
    tool: str,
    frost: str | None,
    info: dict[str, Any],
    jobs: int,
    state_root: pathlib.Path,
    values: dict[str, list[int]],
) -> dict[str, Any]:
    """Change a public constant in Core that Model inlines; touch nothing else.

    Core's reference assembly changes (the constant's value is metadata), so
    Model must recompile even though none of its sources changed. A frontend
    that reused Model's cached assembly would print the old total. Nothing
    above Model sees an API change, so Service and App may be skipped."""
    try:
        write_csharp_constants(root, 5)
        _, observation = run_csharp_tool(root, tool, frost, info, jobs, state_root)
        artifact = verify_csharp_output(
            root, tool, csharp_expected_total(values, extra=5), info, state_root
        )
        return {"status": "passed", "observed": observation, "stdout": artifact["stdout"]}
    except Exception as error:  # recorded in the report, never swallowed
        return {"status": "failed", "reason": str(error)}
    finally:
        write_csharp_constants(root, 0)
        run_csharp_tool(root, tool, frost, info, jobs, state_root)
        verify_csharp_output(root, tool, csharp_expected_total(values), info, state_root)


def probe_toolchain_closure_change(
    root: pathlib.Path,
    tool: str,
    frost: str | None,
    info: dict[str, Any],
    jobs: int,
    state_root: pathlib.Path,
    values: dict[str, list[int]],
) -> dict[str, Any]:
    """Change one byte-level input of the compiler closure (the SDK analysis
    level globalconfig every project passes) without touching any source.

    Every compile action must rerun: if the closure were not in the key, all
    four would be cache hits. The file is replaced, not edited in place,
    because it is hard-linked to the real SDK."""
    configs = sorted(root.glob(".dotnet-sdk/**/analysislevel*.globalconfig")) or sorted(
        root.glob(".dotnet-sdk/**/*.globalconfig")
    )
    if not configs:
        return {"status": "skipped", "reason": "no bundled globalconfig to change"}
    target = configs[0]
    original = target.read_bytes()
    try:
        target.unlink()
        target.write_bytes(original + b"\n# frost-bench toolchain probe\n")
        _, observation = run_csharp_tool(root, tool, frost, info, jobs, state_root)
        verify_csharp_output(root, tool, csharp_expected_total(values), info, state_root)
        compiled = [
            name for name in observation.get("executed_actions", []) if not name.rstrip("]").endswith("_api")
        ]
        return {
            "status": "passed" if len(compiled) == len(CSHARP_PROJECTS) else "failed",
            "changed_file": target.relative_to(root).as_posix(),
            "observed": observation,
            "compile_actions_rerun": len(compiled),
        }
    except Exception as error:
        return {"status": "failed", "reason": str(error)}
    finally:
        target.unlink(missing_ok=True)
        target.write_bytes(original)
        run_csharp_tool(root, tool, frost, info, jobs, state_root)


